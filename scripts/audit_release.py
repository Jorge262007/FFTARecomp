"""Read-only check for ROM/save/dump and generated-game artifacts."""
from pathlib import Path
import hashlib
import sqlite3
import sys
import re

ROOT = Path(__file__).resolve().parents[1]
ROM_SHA1 = '4ac05441f4de70a4ec3dd932116346c61b8783d9'
SUSPECT_SUFFIXES = {'.gba', '.gb', '.gbc', '.sav', '.ffstate', '.srm', '.bios', '.bin', '.dump', '.ppm', '.asm'}
findings = []
files = 0
for path in ROOT.rglob('*'):
    if not path.is_file() or '.git' in path.relative_to(ROOT).parts:
        continue
    rel = path.relative_to(ROOT)
    cache = rel.parts[0] == 'target'
    if cache and '--include-build-cache' not in sys.argv:
        continue  # Build cache is excluded from the source upload.
    files += 1
    if path.suffix.lower() in (SUSPECT_SUFFIXES if not cache else {'.gba', '.gb', '.gbc', '.sav', '.ffstate', '.srm', '.dump', '.ppm'}):
        findings.append(f'REVIEW {rel} ({path.stat().st_size} bytes)')
    try:
        with path.open('rb') as f:
            head = f.read(192)
    except OSError as error:
        findings.append(f'UNREADABLE {rel}: {error}')
        continue
    if len(head) >= 192 and head[0xB2] == 0x96 and head[0xAC:0xB0] == b'AFXE':
        findings.append(f'ROM_HEADER {rel}')
    if path.stat().st_size == 16 * 1024 * 1024:
        if hashlib.sha1(path.read_bytes()).hexdigest() == ROM_SHA1:
            findings.append(f'EXACT_ROM {rel}')
    if path.suffix.lower() in {'.c', '.h', '.rs'}:
        text = path.read_text(encoding='utf-8', errors='replace')
        if 'Generated by recomp' in text and ('uint32_t b_080' in text or 'b_08000000_' in text):
            findings.append(f'GENERATED_GAME_CODE {rel}')
    if re.match(r'^[0-9a-fA-F]{64}.*\.(dll|so|dylib)$', path.name):
        findings.append(f'GENERATED_GAME_LIBRARY {rel}')
for name in ('gamedb.sqlite', 'Installer/payload/gamedb.sqlite'):
    path = ROOT / name
    if path.exists():
        db = sqlite3.connect(f'file:{path.as_posix()}?mode=ro', uri=True)
        print(f'DATABASE {name}')
        for row in db.execute("SELECT sql FROM sqlite_master WHERE type='table'"):
            print(row[0])
        db.close()
print(f'AUDIT files={files} excluded=.git' + ('' if '--include-build-cache' in sys.argv else ',target') + f' findings={len(findings)}')
for finding in findings:
    print(finding)
