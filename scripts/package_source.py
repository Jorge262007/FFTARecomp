"""Create the reviewed source-only set for a manual browser upload."""
from pathlib import Path
from zipfile import ZipFile, ZIP_DEFLATED

root = Path(__file__).resolve().parents[1]
dest = root / 'target/github-upload/FFTARecomp-source.zip'
dest.parent.mkdir(parents=True, exist_ok=True)
directories = {'.github', 'assets', 'crates', 'docs', 'Image', 'scripts', 'tools', 'Licenses'}
suffixes = {'.exe', '.dll', '.so', '.dylib', '.gba', '.gb', '.gbc', '.sav', '.ffstate', '.bin', '.o', '.bak', '.log', '.input', '.ppm', '.asm', '.pyc'}
files = []
for path in root.rglob('*'):
    if not path.is_file():
        continue
    rel = path.relative_to(root)
    if any(part in {'.git', 'target', '__pycache__', 'toolchain', 'tcc', 'node_modules'} for part in rel.parts):
        continue
    if path.suffix.lower() in suffixes:
        continue
    if len(rel.parts) > 1 and rel.parts[0] not in directories:
        if rel.parts[:2] != ('Installer', 'scripts'):
            continue
    files.append(path)
for path in files:
    data = path.read_bytes()
    if len(data) >= 192 and data[0xB2] == 0x96 and data[0xAC:0xB0] == b'AFXE':
        raise RuntimeError(f'ROM header in source upload: {path}')
    if path.suffix in {'.c', '.h', '.rs'} and b'Generated by recomp' in data and b'uint32_t b_080' in data:
        raise RuntimeError(f'Generated game source in upload: {path}')
with ZipFile(dest, 'w', ZIP_DEFLATED) as archive:
    for path in sorted(files):
        archive.write(path, path.relative_to(root).as_posix())
print(f'SOURCE_PACKAGE files={len(files)} bytes={dest.stat().st_size} path={dest}')
